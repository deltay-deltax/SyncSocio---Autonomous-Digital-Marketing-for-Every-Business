import mongoose from 'mongoose';

const strategyCreativeSchema = new mongoose.Schema({
  user: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'User',
    required: true,
    index: true,
  },
  brandId: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'BrandProfile',
    index: true,
  },
  // What was generated
  type: {
    type: String,
    enum: ['image', 'carousel', 'video'],
    required: true,
  },
  // Image: base64 string; Carousel: first slide base64; Video: thumbnail
  thumbnailBase64: {
    type: String,
    default: '',
  },
  // For carousels — all slides
  slides: [{
    image: String,
  }],
  // For videos
  videoUrl: {
    type: String,
    default: '',
  },
  // Caption generated by AI
  caption: {
    type: String,
    default: '',
  },
  // Metadata from the generation request
  idea: {
    type: String,
    default: '',
  },
  aspectRatio: {
    type: String,
    default: '1:1',
  },
  // Status: hearted = saved to library
  status: {
    type: String,
    enum: ['hearted', 'rejected', 'scheduled', 'posted'],
    default: 'hearted',
  },
  scheduledAt: {
    type: Date,
  },
  createdAt: {
    type: Date,
    default: Date.now,
  },
});

strategyCreativeSchema.index({ user: 1, status: 1, createdAt: -1 });

export default mongoose.model('StrategyCreative', strategyCreativeSchema);
